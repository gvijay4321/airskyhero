// Builds the parts of the site that come from heroes.js. Run with: npm run build
//   <slug>/index.html   one page per hero (airskyhero.com/smit-machchhar/), readable by Google
//   share/<slug>.jpg     1200x630 preview image shown when a hero's link is shared
//   share/home.jpg       preview image for the home page
//   sitemap.xml          every page, for Google Search Console
// Preview images need Google Chrome (or set CHROME_PATH); pages and sitemap are written either way.
import fs from "node:fs";
import path from "node:path";
import { createRequire } from "node:module";
import { fileURLToPath } from "node:url";

const ROOT = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
const require = createRequire(import.meta.url);
const HEROES = require(path.join(ROOT, "heroes.js"));
const { SITE, esc, heroSlug, heroPath, heroUrl, shareImage, newsHtml, shareHtml, splitNews } = require(path.join(ROOT, "news.js"));

const MARK = `<!-- Generated by scripts/build.mjs from heroes.js. Edit heroes.js, then run "npm run build". -->`;
const abs = p => (p && !/^https?:/.test(p) ? "/" + p.replace(/^\//, "") : p);
const initials = name => name.replace(/["(].*?[")]/g, "").split(/\s+/).filter(w => /^[A-Z]/.test(w)).map(w => w[0]).slice(0, 2).join("");
const clip = (s, n) => (s.length <= n ? s : s.slice(0, s.lastIndexOf(" ", n - 1)) + "…");
const write = (file, data) => {
  const full = path.join(ROOT, file);
  fs.mkdirSync(path.dirname(full), { recursive: true });
  if (fs.existsSync(full) && Buffer.compare(fs.readFileSync(full), Buffer.from(data)) === 0) return false;
  fs.writeFileSync(full, data);
  return true;
};

// Same order as the home page list: by country, then year.
const ordered = [...HEROES].sort((a, b) => a.country.localeCompare(b.country) || a.year - b.year);
const slugs = new Set();
for (const h of ordered) {
  const s = heroSlug(h);
  if (slugs.has(s)) throw new Error(`Two heroes have the page address "${s}". Give one of them slug: "..." in heroes.js.`);
  slugs.add(s);
}

/* ---------- Hero pages ---------- */
const PLANE = `<svg viewBox="0 0 24 24" fill="currentColor" aria-hidden="true"><path d="M21 16v-2l-8-5V3.5a1.5 1.5 0 0 0-3 0V9l-8 5v2l8-2.5V19l-2 1.5V22l3.5-1 3.5 1v-1.5L13 19v-5.5l8 2.5z"/></svg>`;

const heroCard = h => `
        <a class="card" href="${heroPath(h)}">
          <div class="thumb">${h.image
            ? `<img src="${esc(abs(h.image))}" alt="${esc(h.imageAlt || "")}" class="${h.imageKind === "portrait" ? "face" : ""}" loading="lazy" width="640" height="360">`
            : `<span class="initials" aria-hidden="true">${esc(initials(h.name))}</span>`}</div>
          <h4>${esc(h.name)}</h4>
          <div class="tags"><span class="tag">${esc(h.role)}</span><span class="tag">${h.year}</span></div>
          <p class="flight">${esc(h.flight)}</p>
          <span class="more">Read story →</span>
        </a>`;

// Other heroes from the same flight first, then the same country, then the closest in time.
function related(h) {
  const rank = o => (o.flight === h.flight ? 0 : o.country === h.country ? 1 : 2) * 1e4 + Math.abs(o.year - h.year);
  return HEROES.filter(o => o !== h).sort((a, b) => rank(a) - rank(b)).slice(0, 3);
}

function heroPage(h, i) {
  const title = `${h.name}: ${h.flight} (${h.year}) | AirSkyHero`;
  const description = clip(h.story, 158);
  const prev = ordered[i - 1], next = ordered[i + 1];
  const facts = [
    ["Flight", h.flight], ["Date", h.date], ["Aircraft", h.aircraft], ["Location", h.place],
    ...(h.aboard ? [["Survivors", `${h.survived} of ${h.aboard} aboard`]] : [])
  ];
  const { videos } = splitNews(h);
  const ld = {
    "@context": "https://schema.org", "@type": "Article",
    headline: `${h.name}: ${h.flight}`, description, url: heroUrl(h), image: shareImage(h),
    about: { "@type": h.role === "Passenger" && /^Passengers/.test(h.name) ? "Thing" : "Person", name: h.name, nationality: h.country },
    publisher: { "@type": "Organization", name: "AirSkyHero", url: SITE },
    ...(videos.length ? { video: videos.map(v => ({ "@type": "VideoObject", name: v.title || v.outlet, embedUrl: v.url })) } : {})
  };
  return `<!doctype html>
${MARK}
<html lang="en">
<head>
<meta charset="utf-8">
<meta name="viewport" content="width=device-width, initial-scale=1, viewport-fit=cover">
<title>${esc(title)}</title>
<meta name="description" content="${esc(description)}">
<meta name="theme-color" content="#0b1118">
<link rel="canonical" href="${heroUrl(h)}">
<meta property="og:type" content="article">
<meta property="og:site_name" content="AirSkyHero">
<meta property="og:title" content="${esc(`${h.name}: ${h.flight}`)}">
<meta property="og:description" content="${esc(description)}">
<meta property="og:url" content="${heroUrl(h)}">
<meta property="og:image" content="${shareImage(h)}">
<meta property="og:image:width" content="1200">
<meta property="og:image:height" content="630">
<meta property="og:image:alt" content="${esc(`${h.name}, ${h.role}, ${h.flight}`)}">
<meta name="twitter:card" content="summary_large_image">
<link rel="manifest" href="/manifest.webmanifest">
<link rel="icon" href="/icon.svg" type="image/svg+xml">
<link rel="apple-touch-icon" href="/apple-touch-icon.png">
<link rel="stylesheet" href="/site.css">
<script type="application/ld+json">${JSON.stringify(ld).replace(/</g, "\\u003c")}</script>
</head>
<body>

<header>
  <div class="wrap">
    <a class="logo" href="/" aria-label="AirSkyHero home">
      ${PLANE}
      <span>Air<b>Sky</b>Hero</span>
    </a>
    <nav aria-label="Main">
      <a href="/#map-section">Map</a>
      <a href="/#heroes">Heroes</a>
      <a href="/what-passengers-can-do/">Safety</a>
      <a href="/#about">About</a>
    </nav>
  </div>
</header>

<main class="wrap hero-page">
  <p class="crumbs"><a href="/">Home</a> › <a href="/#heroes">Heroes</a> › ${esc(h.country)}</p>
  <article>
    <div class="hp-head">
      <p class="eyebrow">${esc(h.role)} · ${esc(h.country)}</p>
      <h1>${esc(h.name)}</h1>
      <div class="tags"><span class="tag">${esc(h.flight)}</span><span class="tag">${h.year}</span>${h.developing ? '<span class="badge-live">Developing story</span>' : ""}</div>
    </div>
${h.image ? `    <figure class="hp-photo">
      <img src="${esc(abs(h.image))}" alt="${esc(h.imageAlt || "")}">
${h.imageCredit ? `      <figcaption>Photo: <a href="${esc(h.imageCreditUrl || "")}" target="_blank" rel="noopener">${esc(h.imageCredit)}</a></figcaption>\n` : ""}    </figure>
` : ""}    <dl class="facts">
${facts.map(([k, v]) => `      <div class="fact"><dt>${k}</dt><dd>${esc(v)}</dd></div>`).join("\n")}
    </dl>
${h.developing ? `    <p class="developing">This is a recent event and an investigation is under way. Details may change as more is confirmed.</p>\n` : ""}    <p class="hp-story">${esc(h.story)}</p>
    <p class="hp-source">Source: <a href="${esc(h.source)}" target="_blank" rel="noopener">${esc(h.source.replace(/^https?:\/\/(www\.)?/, ""))} ↗</a></p>
    <p class="hp-guide">If something goes wrong on your flight: <a href="/what-passengers-can-do/">what passengers can do, close by or farther away →</a></p>
    ${shareHtml(h)}
    <section class="news" aria-labelledby="d-news-h">${newsHtml(h)}
    </section>
  </article>

  <section class="hp-more" aria-labelledby="more-h">
    <h2 id="more-h">More heroes</h2>
    <div class="grid">${related(h).map(heroCard).join("")}
    </div>
    <nav class="hp-pager" aria-label="Previous and next hero">
      <span>${prev ? `<a href="${heroPath(prev)}">← ${esc(prev.name)}</a>` : ""}</span>
      <span>${next ? `<a href="${heroPath(next)}">${esc(next.name)} →</a>` : ""}</span>
    </nav>
    <a class="hp-home" href="/#heroes">See all heroes on the world map →</a>
  </section>
</main>

<script src="/news.js"></script>
<script data-goatcounter="https://airskyhero.goatcounter.com/count" async src="https://gc.zgo.at/count.js"></script>
<script>
if ("serviceWorker" in navigator && location.protocol === "https:") navigator.serviceWorker.register("/sw.js");
</script>
</body>
</html>
`;
}

let changed = 0;
ordered.forEach((h, i) => { if (write(`${heroSlug(h)}/index.html`, heroPage(h, i))) changed++; });

// Remove pages of heroes that were deleted or renamed (only folders this script made).
for (const d of fs.readdirSync(ROOT, { withFileTypes: true })) {
  const page = path.join(ROOT, d.name, "index.html");
  if (d.isDirectory() && !slugs.has(d.name) && fs.existsSync(page) && fs.readFileSync(page, "utf8").includes(MARK)) {
    fs.rmSync(path.join(ROOT, d.name), { recursive: true });
    console.log(`Removed old page /${d.name}/`);
  }
}
console.log(`Hero pages: ${ordered.length} (${changed} updated)`);

/* ---------- Sitemap ---------- */
const today = new Date().toISOString().slice(0, 10);
const urls = [`${SITE}/`, `${SITE}/what-passengers-can-do/`, ...ordered.map(heroUrl)];
write("sitemap.xml", `<?xml version="1.0" encoding="UTF-8"?>
<urlset xmlns="http://www.sitemaps.org/schemas/sitemap/0.9">
${urls.map(u => `  <url>\n    <loc>${u}</loc>\n    <lastmod>${today}</lastmod>\n  </url>`).join("\n")}
</urlset>
`);
console.log(`Sitemap: ${urls.length} addresses`);

/* ---------- Share images (1200x630) ---------- */
const dataUri = p => {
  const file = path.join(ROOT, p);
  const type = path.extname(file).toLowerCase() === ".png" ? "image/png" : "image/jpeg";
  return `data:${type};base64,${fs.readFileSync(file).toString("base64")}`;
};
