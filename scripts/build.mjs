// Other heroes from the same flight first, then the same country, then the closest in time.
function related(h) {
  const rank = o => (o.flight === h.flight ? 0 : o.country === h.country ? 1 : 2) * 1e4 + Math.abs(o.year - h.year);
  return HEROES.filter(o => o !== h).sort((a, b) => rank(a) - rank(b)).slice(0, 3);
}

