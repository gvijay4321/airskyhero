const CHROME = [process.env.CHROME_PATH,
  "C:/Program Files/Google/Chrome/Application/chrome.exe",
  "C:/Program Files (x86)/Google/Chrome/Application/chrome.exe",
  "C:/Program Files (x86)/Microsoft/Edge/Application/msedge.exe",
  "/Applications/Google Chrome.app/Contents/MacOS/Google Chrome",
  "/usr/bin/google-chrome", "/usr/bin/chromium"].find(p => p && fs.existsSync(p));

if (!CHROME) {
  console.warn("Share images skipped: Chrome not found (set CHROME_PATH to its location).");
} else {
  const { default: puppeteer } = await import("puppeteer-core");
  const browser = await puppeteer.launch({ executablePath: CHROME, headless: true });
  try {
    const page = await browser.newPage();
    await page.setViewport({ width: 1200, height: 630, deviceScaleFactor: 1 });
    const shoot = async (file, html) => {
      await page.setContent(html, { waitUntil: "load" });
      await page.evaluate(() => document.fonts.ready);
      return write(file, await page.screenshot({ type: "jpeg", quality: 85 }));
    };
    let n = 0;
    for (const h of ordered) if (await shoot(`share/${heroSlug(h)}.jpg`, heroCardHtml(h))) n++;
    if (await shoot("share/home.jpg", homeCardHtml())) n++;
    for (const f of fs.readdirSync(path.join(ROOT, "share"))) {
      if (f !== "home.jpg" && !slugs.has(f.replace(/\.jpg$/, ""))) fs.rmSync(path.join(ROOT, "share", f));
    }
    console.log(`Share images: ${ordered.length + 1} (${n} updated)`);
  } finally {
    await browser.close();
  }
}
