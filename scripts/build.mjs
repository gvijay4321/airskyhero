// Builds the parts of the site that come from heroes.js. Run with: npm run build
//   <slug>/index.html   one page per hero (airskyhero.com/smit-machchhar/), readable by Google
//   share/<slug>.jpg     1200x630 preview image shown when a hero's link is shared
//   share/home.jpg       preview image for the home page
//   sitemap.xml          every page, for Google Search Console
// Preview images need Google Chrome (or set CHROME_PATH); pages and sitemap are written either way.
import fs from "node:fs";
import path from "node:path";
import { createRequire } from "node:module";
import { fileURLToPath } from "node:url";

const ROOT = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
const require = createRequire(import.meta.url);
const HEROES = require(path.join(ROOT, "heroes.js"));
const HELPERS = require(path.join(ROOT, "helpers.js"));
const KINDNESS = require(path.join(ROOT, "kindness.js"));
const KIND_SLUG = "acts-of-kindness";
const { SITE, esc, heroSlug, heroPath, heroUrl, shareImage, newsHtml, helpersHtml, developingText, shareHtml, splitNews } = require(path.join(ROOT, "news.js"));

const MARK = `<!-- Generated by scripts/build.mjs from heroes.js. Edit heroes.js, then run "npm run build". -->`;
const abs = p => (p && !/^https?:/.test(p) ? "/" + p.replace(/^\//, "") : p);
const initials = name => name.replace(/["(].*?[")]/g, "").split(/\s+/).filter(w => /^[A-Z]/.test(w)).map(w => w[0]).slice(0, 2).join("");
const clip = (s, n) => (s.length <= n ? s : s.slice(0, s.lastIndexOf(" ", n - 1)) + "…");
const write = (file, data) => {
  const full = path.join(ROOT, file);
  fs.mkdirSync(path.dirname(full), { recursive: true });
  if (fs.existsSync(full) && Buffer.compare(fs.readFileSync(full), Buffer.from(data)) === 0) return false;
  fs.writeFileSync(full, data);
  return true;
};

// Same order as the home page list: by country, then year.
const ordered = [...HEROES].sort((a, b) => a.country.localeCompare(b.country) || a.year - b.year);
const slugs = new Set();
for (const h of ordered) {
  const s = heroSlug(h);
  if (s === KIND_SLUG) throw new Error(`"${s}" is the Acts of kindness page. Give this hero another slug in heroes.js.`);
  if (slugs.has(s)) throw new Error(`Two heroes have the page address "${s}". Give one of them slug: "..." in heroes.js.`);
  slugs.add(s);
}

// Every news link belongs on one hero's page only, so no two pages list the same story.
{
  const seen = new Map();
  for (const h of HEROES) for (const n of h.news || []) {
    if (seen.has(n.url)) throw new Error(`"${n.url}" is in the news of both ${seen.get(n.url)} and ${h.name}. Keep it on one of them in heroes.js.`);
    seen.set(n.url, h.name);
  }
}

