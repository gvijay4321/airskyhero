//   <slug>/index.html   one page per hero (airskyhero.com/smit-machchhar/), readable by Google
//   share/<slug>.jpg     1200x630 preview image shown when a hero's link is shared
//   share/home.jpg       preview image for the home page
//   sitemap.xml          every page, for Google Search Console
// Preview images need Google Chrome (or set CHROME_PATH); pages and sitemap are written either way.
