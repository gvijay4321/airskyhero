/* ---------- No repeated text ---------- */
// Google can treat pages that share the same paragraphs as duplicates and leave some out of search.
// Stop the build if any sentence-length piece of text (60+ characters) appears on more than one page.
{
  const pages = ["index.html", ...urls.slice(1).map(u => u.slice(SITE.length + 1) + "index.html")];
  const where = new Map();
  for (const p of pages) {
    const html = fs.readFileSync(path.join(ROOT, p), "utf8")
      .replace(/<head>[\s\S]*?<\/head>|<header>[\s\S]*?<\/header>|<script[\s\S]*?<\/script>|<style[\s\S]*?<\/style>/g, "");
    const blocks = html.split(/<\/?(?:p|li|h\d|summary|details|figcaption|dd|dt|div|span|a|section|td)\b[^>]*>/)
      .map(t => t.replace(/<[^>]+>/g, " ").replace(/&[a-z#0-9]+;/g, " ").replace(/\s+/g, " ").trim()).filter(t => t.length >= 60);
    for (const b of new Set(blocks)) where.set(b, [...(where.get(b) || []), p]);
  }
  const repeats = [...where].filter(([, ps]) => ps.length > 1);
  if (repeats.length) throw new Error("The same text is on more than one page:\n" +
    repeats.map(([b, ps]) => `  "${b.slice(0, 90)}…" on ${ps.join(", ")}`).join("\n"));
  console.log(`Repeated text: none across ${pages.length} pages`);
}

